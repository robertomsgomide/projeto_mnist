    signal palavra : std_logic_vector(DATA_WIDTH_C-1 downto 0) := (others => '0');

begin

    -- Leitura sincrona.
    -- ROM_PESOS_S tem ROM_DEPTH_C = 1024 posicoes.
    -- Enderecos 0..783 contem pesos reais.
    -- Enderecos 784..1023 sao zerados.
    process(clock)
    begin
        if rising_edge(clock) then
            palavra <= ROM_PESOS_S(to_integer(endereco_pixel));
        end if;
    end process;

    -- Desempacota os 10 pesos para o array tipado.
    -- Ordenacao: pesos_pixel(0) ocupa os bits menos significativos.
    gen_unpack: for d in 0 to NUM_DIGITOS_C-1 generate
        pesos_pixel(d) <= signed(palavra((d+1)*PESO_WIDTH_C-1 downto d*PESO_WIDTH_C));
    end generate;

end architecture arch;
