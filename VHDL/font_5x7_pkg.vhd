library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

package font_5x7_pkg is

    constant FONT_W_C : natural := 5;
    constant FONT_H_C : natural := 7;

    type linha_font_t is array (0 to FONT_H_C-1)
        of std_logic_vector(FONT_W_C-1 downto 0);
    type font_digitos_t is array (0 to 9) of linha_font_t;

    constant FONT_DIGITOS_C : font_digitos_t := (
        0 => ("01110", "10001", "10011", "10101", "11001", "10001", "01110"),
        1 => ("00100", "01100", "00100", "00100", "00100", "00100", "01110"),
        2 => ("01110", "10001", "00001", "00010", "00100", "01000", "11111"),
        3 => ("11110", "00001", "00001", "01110", "00001", "00001", "11110"),
        4 => ("00010", "00110", "01010", "10010", "11111", "00010", "00010"),
        5 => ("11111", "10000", "11110", "00001", "00001", "10001", "01110"),
        6 => ("00110", "01000", "10000", "11110", "10001", "10001", "01110"),
        7 => ("11111", "00001", "00010", "00100", "01000", "01000", "01000"),
        8 => ("01110", "10001", "10001", "01110", "10001", "10001", "01110"),
        9 => ("01110", "10001", "10001", "01111", "00001", "00010", "01100")
    );

    function pixel_font(d : integer; col : integer; row : integer) return std_logic;
    function pixel_char(c : character; col : integer; row : integer) return std_logic;

end package font_5x7_pkg;

package body font_5x7_pkg is

    subtype glyph_t is std_logic_vector(FONT_W_C * FONT_H_C - 1 downto 0);

    function glyph_char(c : character) return glyph_t is
    begin
        case c is
            when '0' => return "01110" & "10001" & "10011" & "10101" & "11001" & "10001" & "01110";
            when '1' => return "00100" & "01100" & "00100" & "00100" & "00100" & "00100" & "01110";
            when '2' => return "01110" & "10001" & "00001" & "00010" & "00100" & "01000" & "11111";
            when '3' => return "11110" & "00001" & "00001" & "01110" & "00001" & "00001" & "11110";
            when '4' => return "00010" & "00110" & "01010" & "10010" & "11111" & "00010" & "00010";
            when '5' => return "11111" & "10000" & "11110" & "00001" & "00001" & "10001" & "01110";
            when '6' => return "00110" & "01000" & "10000" & "11110" & "10001" & "10001" & "01110";
            when '7' => return "11111" & "00001" & "00010" & "00100" & "01000" & "01000" & "01000";
            when '8' => return "01110" & "10001" & "10001" & "01110" & "10001" & "10001" & "01110";
            when '9' => return "01110" & "10001" & "10001" & "01111" & "00001" & "00010" & "01100";

            when 'A' | 'a' => return "01110" & "10001" & "10001" & "11111" & "10001" & "10001" & "10001";
            when 'B' | 'b' => return "11110" & "10001" & "10001" & "11110" & "10001" & "10001" & "11110";
            when 'C' | 'c' => return "01110" & "10001" & "10000" & "10000" & "10000" & "10001" & "01110";
            when 'D' | 'd' => return "11110" & "10001" & "10001" & "10001" & "10001" & "10001" & "11110";
            when 'E' | 'e' => return "11111" & "10000" & "10000" & "11110" & "10000" & "10000" & "11111";
            when 'F' | 'f' => return "11111" & "10000" & "10000" & "11110" & "10000" & "10000" & "10000";
            when 'G' | 'g' => return "01110" & "10001" & "10000" & "10111" & "10001" & "10001" & "01110";
            when 'H' | 'h' => return "10001" & "10001" & "10001" & "11111" & "10001" & "10001" & "10001";
            when 'I' | 'i' => return "01110" & "00100" & "00100" & "00100" & "00100" & "00100" & "01110";
            when 'J' | 'j' => return "00111" & "00010" & "00010" & "00010" & "10010" & "10010" & "01100";
            when 'K' | 'k' => return "10001" & "10010" & "10100" & "11000" & "10100" & "10010" & "10001";
            when 'L' | 'l' => return "10000" & "10000" & "10000" & "10000" & "10000" & "10000" & "11111";
            when 'M' | 'm' => return "10001" & "11011" & "10101" & "10101" & "10001" & "10001" & "10001";
            when 'N' | 'n' => return "10001" & "11001" & "10101" & "10011" & "10001" & "10001" & "10001";
            when 'O' | 'o' => return "01110" & "10001" & "10001" & "10001" & "10001" & "10001" & "01110";
            when 'P' | 'p' => return "11110" & "10001" & "10001" & "11110" & "10000" & "10000" & "10000";
            when 'Q' | 'q' => return "01110" & "10001" & "10001" & "10001" & "10101" & "10010" & "01101";
            when 'R' | 'r' => return "11110" & "10001" & "10001" & "11110" & "10100" & "10010" & "10001";
            when 'S' | 's' => return "01111" & "10000" & "10000" & "01110" & "00001" & "00001" & "11110";
            when 'T' | 't' => return "11111" & "00100" & "00100" & "00100" & "00100" & "00100" & "00100";
            when 'U' | 'u' => return "10001" & "10001" & "10001" & "10001" & "10001" & "10001" & "01110";
            when 'V' | 'v' => return "10001" & "10001" & "10001" & "10001" & "10001" & "01010" & "00100";
            when 'W' | 'w' => return "10001" & "10001" & "10001" & "10101" & "10101" & "10101" & "01010";
            when 'X' | 'x' => return "10001" & "10001" & "01010" & "00100" & "01010" & "10001" & "10001";
            when 'Y' | 'y' => return "10001" & "10001" & "01010" & "00100" & "00100" & "00100" & "00100";
            when 'Z' | 'z' => return "11111" & "00001" & "00010" & "00100" & "01000" & "10000" & "11111";

            when ':' => return "00000" & "00100" & "00100" & "00000" & "00100" & "00100" & "00000";
            when '.' => return "00000" & "00000" & "00000" & "00000" & "00000" & "01100" & "01100";
            when ',' => return "00000" & "00000" & "00000" & "00000" & "01100" & "01100" & "01000";
            when '%' => return "11001" & "11010" & "00100" & "01000" & "10011" & "00110" & "00000";
            when '-' => return "00000" & "00000" & "00000" & "11111" & "00000" & "00000" & "00000";
            when '>' => return "10000" & "01000" & "00100" & "00010" & "00100" & "01000" & "10000";
            when '/' => return "00001" & "00010" & "00100" & "01000" & "10000" & "00000" & "00000";
            when '|' => return "00100" & "00100" & "00100" & "00100" & "00100" & "00100" & "00100";
            when '~' => return "00000" & "00000" & "01000" & "10101" & "00010" & "00000" & "00000";
            when '?' => return "01110" & "10001" & "00001" & "00010" & "00100" & "00000" & "00100";
            when others => return (others => '0');
        end case;
    end function;

    function pixel_font(d : integer; col : integer; row : integer) return std_logic is
    begin
        if d < 0 or d > 9 then
            return '0';
        elsif col < 0 or col >= FONT_W_C or row < 0 or row >= FONT_H_C then
            return '0';
        else
            return FONT_DIGITOS_C(d)(row)(FONT_W_C-1 - col);
        end if;
    end function;

    function pixel_char(c : character; col : integer; row : integer) return std_logic is
        variable glyph : glyph_t;
        variable idx   : natural range 0 to FONT_W_C * FONT_H_C - 1;
    begin
        if col < 0 or col >= FONT_W_C or row < 0 or row >= FONT_H_C then
            return '0';
        else
            glyph := glyph_char(c);
            idx := (FONT_H_C - 1 - row) * FONT_W_C + (FONT_W_C - 1 - col);
            return glyph(idx);
        end if;
    end function;

end package body font_5x7_pkg;
